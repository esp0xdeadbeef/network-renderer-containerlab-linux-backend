    "capabilities": {"labEmulation": True},
    "labEmulation": {
        "scope": "harness",
        "requests": [
            {
                "providerEmulationMode": "fake-provider",
                "name": "fake-isp-a",
                "handoffVlan": 11,
                "liveUpstreamVlan": 4,
                "clientSideVlan": 12,
            }
        ],
    },
}
fake_artifacts = render_lab_emulation_artifacts(site(fake_provider))
assert fake_artifacts == [
    {
        "providerEmulationMode": "fake-provider",
        "name": "fake-isp-a",
        "handoffVlan": 11,
        "liveUpstreamVlan": 4,
        "clientSideVlan": 12,
        "scope": "harness",
        "harnessScoped": True,
        "ordinaryTargetOutput": False,
        "providerToCoreHandoff": {"vlan": 11},
        "liveUpstreamReachability": {"vlan": 4},
        "isolatedClientSide": {"vlan": 12},
    }
]

