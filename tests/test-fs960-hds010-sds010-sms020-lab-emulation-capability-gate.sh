import json
import tempfile
from pathlib import Path

from clabgen.models import SiteModel
from clabgen.s88.CM.lab_emulation import render_lab_emulation_artifacts
from clabgen.s88.enterprise.site_loader import load_sites
from clabgen.s88.site.topology import render_site_topology


def site(containerlab):
    return SiteModel(
        enterprise="test",
        site="site-a",
        nodes={},
        links={},
        single_access="",
        domains={},
        renderer_inventory={"containerlab": containerlab},
    )


def assert_refuses(containerlab, expected):
    try:
        render_lab_emulation_artifacts(site(containerlab))
    except ValueError as exc:
        message = str(exc)
        if expected not in message:
            raise AssertionError(f"expected {expected!r} in {message!r}") from exc
    else:
        raise AssertionError(f"expected refusal containing {expected!r}")


def assert_topology_refuses_without_artifacts(containerlab, expected):
    try:
        render_site_topology(site(containerlab))
    except ValueError as exc:
        message = str(exc)
        if expected not in message:
            raise AssertionError(f"expected {expected!r} in {message!r}") from exc
    else:
        raise AssertionError("expected topology render refusal before backend artifact emission")


